USE ordersystem_bench;

TRUNCATE TABLE bench_read_records;
TRUNCATE TABLE bench_update_records;
TRUNCATE TABLE bench_delete_records;
TRUNCATE TABLE bench_insert_records;

-- 生成 1 到 1,000,000 的主键，供读、更新和删除测试使用。
-- 这里直接使用六份独立的数字集合，避免 MySQL 临时表在同一条查询中被重复引用。
INSERT INTO bench_read_records (id, value)
SELECT numbers.n + 1, MOD(numbers.n + 1, 100000)
FROM
(
    SELECT a.digit
        + b.digit * 10
        + c.digit * 100
        + d.digit * 1000
        + e.digit * 10000
        + f.digit * 100000 AS n
    FROM
        (SELECT 0 AS digit UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4 UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) AS a
    CROSS JOIN
        (SELECT 0 AS digit UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4 UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) AS b
    CROSS JOIN
        (SELECT 0 AS digit UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4 UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) AS c
    CROSS JOIN
        (SELECT 0 AS digit UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4 UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) AS d
    CROSS JOIN
        (SELECT 0 AS digit UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4 UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) AS e
    CROSS JOIN
        (SELECT 0 AS digit UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4 UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) AS f
) AS numbers
WHERE numbers.n < 1000000;

INSERT INTO bench_update_records (id, value)
SELECT id, value FROM bench_read_records;

INSERT INTO bench_delete_records (id, value)
SELECT id, value FROM bench_read_records;

SELECT 'read' AS table_name, COUNT(*) AS total
FROM bench_read_records
UNION ALL
SELECT 'update', COUNT(*)
FROM bench_update_records
UNION ALL
SELECT 'delete', COUNT(*)
FROM bench_delete_records
UNION ALL
SELECT 'insert', COUNT(*)
FROM bench_insert_records;
